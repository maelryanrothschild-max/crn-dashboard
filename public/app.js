async function doLogin(){
  const btn = document.querySelector(".login-card .btn");
  const surname = document.getElementById("loginSurname").value.trim();
  const pin = document.getElementById("loginPin").value.trim();
  if(btn){ btn.disabled = true; btn.textContent = "Проверка…"; }
  try{
    const data = await apiLogin(surname, pin);
    currentUser = data.user;
    loginError = "";
    viewMode = "dashboard";
    render();
  }catch(e){
    loginError = e.message || "Неверная фамилия или личный номер. Проверьте данные и попробуйте снова.";
    renderLogin();
  }
}

