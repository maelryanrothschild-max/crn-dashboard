function applyFilters(list){
  let out = list;
  if(searchQuery){
    const q = searchQuery.toLowerCase();
    out = out.filter(e => (e.surname+" "+e.firstname).toLowerCase().includes(q));
  }
  if(filterCity) out = out.filter(e => e.city === filterCity);
  if(filterStore) out = out.filter(e => e.store === filterStore);
  if(filterBrand) out = out.filter(e => e.brand === filterBrand);
  if(filterRole) out = out.filter(e => e.role === filterRole);
  return out;
}

function uniqueVals(list, key){
  return Array.from(new Set(list.map(e => e[key]).filter(Boolean))).sort();
}

