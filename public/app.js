async function importExcel(){
  const input = document.getElementById("excelImportInput");
  const resultBox = document.getElementById("importResult");
  if(!input.files || !input.files[0]){ resultBox.innerHTML = '<div class="error-msg">Выберите файл .xlsx</div>'; return; }

  const file = input.files[0];
  const reader = new FileReader();
  reader.onload = async (e) => {
    try{
      const data = new Uint8Array(e.target.result);
      const wb = XLSX.read(data, {type:"array"});
      const sheet = wb.Sheets[wb.SheetNames[0]];
      const rows = XLSX.utils.sheet_to_json(sheet, {defval:""});

      const employees = rows.map(r => {
        const get = (names) => { for(const n of names){ if(r[n] !== undefined && r[n] !== "") return String(r[n]).trim(); } return ""; };
        const surname = get(["Фамилия","фамилия"]);
        const firstname = get(["Имя","имя"]);
        const roleRu = get(["Должность","должность","Роль","роль"]).toLowerCase();
        const role = ROLE_RU_TO_KEY[roleRu] || "stylist";
        const city = get(["Город","город"]);
        const store = get(["Магазин","магазин"]);
        const brand = get(["Бренд","бренд"]);
        return {surname, firstname, role, city, store, brand};
      }).filter(e => e.surname && e.firstname);

      if(!employees.length){ resultBox.innerHTML = '<div class="error-msg">В файле не найдено ни одной строки с Фамилией и Именем.</div>'; return; }

      const data2 = await apiBulkAddEmployees(employees);
      roster = data2.roster;
      resultBox.innerHTML = '<div class="info-msg">Добавлено сотрудников: '+data2.added.length+'. Личные номера присвоены автоматически.</div>';
      render();
    }catch(err){
      resultBox.innerHTML = '<div class="error-msg">Не удалось прочитать файл: '+err.message+'</div>';
    }
  };
  reader.readAsArrayBuffer(file);
}

