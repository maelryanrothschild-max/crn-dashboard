async function downloadBackup(){
  const backup = await apiGetBackup();
  const blob = new Blob([JSON.stringify(backup, null, 2)], {type:"application/json"});
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "crn_backup_"+new Date().toISOString().slice(0,10)+".json";
  a.click();
  URL.revokeObjectURL(url);
}
async function restoreBackup(){
  const input = document.getElementById("backupRestoreInput");
  const resultBox = document.getElementById("restoreResult");
  if(!input.files || !input.files[0]){ resultBox.innerHTML = '<div class="error-msg">Выберите файл резервной копии .json</div>'; return; }
  if(!confirm("Текущие данные будут полностью заменены содержимым файла. Продолжить?")) return;
  const file = input.files[0];
  const reader = new FileReader();
  reader.onload = async (e) => {
    try{
      const backup = JSON.parse(e.target.result);
      await apiRestoreBackup(backup);
      resultBox.innerHTML = '<div class="info-msg">Восстановлено успешно. Обновите страницу.</div>';
      roster = null;
      render();
    }catch(err){
      resultBox.innerHTML = '<div class="error-msg">Не удалось восстановить: '+err.message+'</div>';
    }
  };
  reader.readAsText(file);
}

