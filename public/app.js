function startQuiz(blockKey){
  activeBlockKey = blockKey;
  quizAnswers = {};
  quizResult = null;
  viewMode = "quiz";
  render();
}
function quizHtml(blockKey){
  const b = allBlocks().find(x=>x.key===blockKey);
  const passScore = Math.ceil((b.quiz.length) * 0.7);
  let resultHtml = "";
  if(quizResult){
    resultHtml = '<div class="quiz-result '+(quizResult.passed?'pass':'fail')+'">'+quizResult.score+'/'+b.quiz.length+' — '+(quizResult.passed ? "Тест пройден!" : "Нужно пересдать (минимум "+passScore+"/"+b.quiz.length+")")+'</div>';
  }
  const qHtml = b.quiz.map((q,qi)=>{
    const optHtml = q.options.map((opt,oi)=>{
      let cls = "";
      if(quizResult){
        if(oi === q.correct) cls = "correct";
        else if(quizAnswers[qi] === oi) cls = "incorrect";
      }
      const checkedAttr = quizAnswers[qi]===oi ? "checked" : "";
      const disAttr = quizResult ? "disabled" : "";
      return '<label class="'+cls+'"><input type="radio" name="q'+qi+'" value="'+oi+'" '+disAttr+' '+checkedAttr+' onchange="setAnswer('+qi+','+oi+')"> '+opt+'</label>';
    }).join("");
    return '<div class="quiz-q"><div class="qtext">'+(qi+1)+'. '+q.q+'</div>'+optHtml+'</div>';
  }).join("");

  const actionHtml = !quizResult
    ? '<div class="actions"><button class="btn btn-gold" onclick="submitQuiz(\''+blockKey+'\')">Проверить тест</button></div>'
    : '<div class="actions"><button class="btn" onclick="backFromQuiz()">Вернуться к блоку</button>'+(!quizResult.passed?'<button class="btn btn-outline" onclick="startQuiz(\''+blockKey+'\')">Пройти ещё раз</button>':'')+'</div>';

  return `
    <button class="backlink" onclick="backFromQuiz()">← Назад к блоку</button>
    <div class="panel">
      <h2>Тест: ${b.title}</h2>
      ${resultHtml}
      ${qHtml}
      ${actionHtml}
    </div>
  `;
}
function setAnswer(qi, oi){ quizAnswers[qi] = oi; }
async function submitQuiz(blockKey){
  const b = allBlocks().find(x=>x.key===blockKey);
  let score = 0;
  b.quiz.forEach((q,qi)=>{ if(quizAnswers[qi] === q.correct) score++; });
  const passScore = Math.ceil(b.quiz.length * 0.7);
  const passed = score >= passScore;
  quizResult = {score, passed};

  const empId = currentUser.id;
  const progress = await loadProgress(empId);
  const p = progress[blockKey] || {};
  p.testScore = score;
  p.testPassed = passed;
  p.done = true;
  p.updatedAt = new Date().toISOString();
  progress[blockKey] = p;
  await saveProgress(empId, progress);
  render();
}
function backFromQuiz(){ viewMode = "block"; quizResult = null; render(); }

